#!/usr/bin/env node
// Write a config.js for a STATICALLY hosted client (GitHub Pages, Netlify,
// itch.io ...). server/index.js generates /config.js itself; a static host
// cannot, so the file has to be baked at build time.
//
//   node server/static-config.mjs dist/web/config.js --server https://mca.example.com
//       reads https://mca.example.com/config.js and mirrors it (paywall, store,
//       product), pointing relayUrl / apiBase at that server
//
//   node server/static-config.mjs dist/web/config.js --relay wss://relay.example.com/ws
//       multiplayer relay only: no store, no paywall
//
// Flags: --server URL | --relay URL --api URL --paywall off|multiplayer|full
//        --store-enabled --redeem-enabled --product-name TEXT --price-label TEXT
// Remember on the server: ALLOWED_ORIGINS=<the static site's origin> and
// PUBLIC_URL=<the static site's URL> (see docs/ONLINE.md).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

function fail(message) {
  process.stderr.write('static-config: ' + message + '\n');
  process.exit(1);
}

function jsLiteral(value) {
  return JSON.stringify(value, null, 2)
    .replace(/</g, '\\u003c')
    .replace(/>/g, '\\u003e')
    .replace(/&/g, '\\u0026')
    .split(String.fromCharCode(0x2028)).join('\\u2028')
    .split(String.fromCharCode(0x2029)).join('\\u2029');
}

export function renderConfig(cfg) {
  return '// Generated by server/static-config.mjs for a statically hosted client.\n'
    + 'window.MCA_CONFIG = Object.assign(' + jsLiteral(cfg) + ', window.MCA_CONFIG || {});\n';
}

// The object literal inside a server-generated /config.js (it is plain JSON).
export function parseServerConfig(source) {
  const start = source.indexOf('Object.assign(');
  const end = source.lastIndexOf(', window.MCA_CONFIG');
  if (start < 0 || end < 0) throw new Error('not a server-generated config.js');
  const cfg = JSON.parse(source.slice(start + 'Object.assign('.length, end));
  if (!cfg || typeof cfg !== 'object' || Array.isArray(cfg)) throw new Error('unexpected config shape');
  return cfg;
}

function checkUrl(value, protocols, flag) {
  let u;
  try { u = new URL(value); } catch (e) { fail(flag + ' must be an absolute URL'); }
  if (!protocols.includes(u.protocol)) fail(flag + ' must start with ' + protocols.map((p) => p + '//').join(' or '));
  return u;
}

export async function buildConfig(opts, fetchImpl = globalThis.fetch) {
  let cfg = {
    relayUrl: '',
    apiBase: '',
    paywall: 'off',
    storeEnabled: false,
    redeemEnabled: false,
    product: { name: "Founder's Pass", priceLabel: '' },
  };
  if (opts.server) {
    const server = checkUrl(opts.server, ['https:', 'http:'], '--server');
    const res = await fetchImpl(new URL('/config.js', server), { redirect: 'error' });
    if (!res.ok) throw new Error('GET ' + server.origin + '/config.js answered ' + res.status);
    cfg = { ...cfg, ...parseServerConfig(await res.text()) };
    if (!cfg.relayUrl) cfg.relayUrl = (server.protocol === 'https:' ? 'wss://' : 'ws://') + server.host + '/ws';
    if (!cfg.apiBase) cfg.apiBase = server.origin;
  }
  if (opts.relay) cfg.relayUrl = checkUrl(opts.relay, ['wss:', 'ws:'], '--relay').href.replace(/\/$/, '');
  if (opts.api) cfg.apiBase = checkUrl(opts.api, ['https:', 'http:'], '--api').origin;
  if (opts.paywall) {
    if (!['off', 'multiplayer', 'full'].includes(opts.paywall)) fail('--paywall must be off, multiplayer or full');
    cfg.paywall = opts.paywall;
  }
  if (opts.storeEnabled) cfg.storeEnabled = true;
  if (opts.redeemEnabled) cfg.redeemEnabled = true;
  if (opts.productName || opts.priceLabel !== undefined) {
    cfg.product = {
      name: opts.productName || (cfg.product && cfg.product.name) || "Founder's Pass",
      priceLabel: opts.priceLabel !== undefined ? opts.priceLabel : ((cfg.product && cfg.product.priceLabel) || ''),
    };
  }
  // A store or paywall without a server to talk to would be a lie.
  if ((cfg.storeEnabled || cfg.redeemEnabled || cfg.paywall !== 'off') && !cfg.apiBase) {
    fail('a store / paywall needs --api (or --server): the static client must know which server verifies licenses');
  }
  return cfg;
}

function parseArgs(argv) {
  const opts = {};
  const rest = [];
  const take = { '--server': 'server', '--relay': 'relay', '--api': 'api', '--paywall': 'paywall', '--product-name': 'productName', '--price-label': 'priceLabel' };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (take[a]) {
      if (i + 1 >= argv.length) fail(a + ' needs a value');
      opts[take[a]] = argv[++i];
    } else if (a === '--store-enabled') opts.storeEnabled = true;
    else if (a === '--redeem-enabled') opts.redeemEnabled = true;
    else if (a.startsWith('--')) fail('unknown flag ' + a);
    else rest.push(a);
  }
  if (rest.length !== 1) fail('usage: node server/static-config.mjs <out-file> [--server URL | --relay URL ...]');
  opts.out = rest[0];
  return opts;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const opts = parseArgs(process.argv.slice(2));
  try {
    const cfg = await buildConfig(opts);
    fs.mkdirSync(path.dirname(path.resolve(opts.out)), { recursive: true });
    fs.writeFileSync(opts.out, renderConfig(cfg));
    process.stdout.write('wrote ' + opts.out + '\n' + JSON.stringify(cfg, null, 2) + '\n');
  } catch (e) {
    fail(e.message);
  }
}
